// 지정한 자모 수 범위(min ~ max)에 맞춰 무작위 단어를 뽑는 함수
export function getRandomWordByJamoCount(min: number, max: number): WordItem {
  const filtered = ALL_WORDS.filter((item) => {
    const count = getJamoCount(item.word);
    return count >= min && count <= max;
  });

  // 해당 범위 조건에 맞는 단어가 없을 경우 전체 단어 중 무작위 선택
  if (filtered.length === 0) {
    return ALL_WORDS[Math.floor(Math.random() * ALL_WORDS.length)];
  }

  const randomIndex = Math.floor(Math.random() * filtered.length);
  return filtered[randomIndex];
}